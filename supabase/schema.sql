-- SpeakUp AI - Supabase PostgreSQL Schema & Row Level Security (RLS)
-- Run this SQL in your Supabase Project -> SQL Editor

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. User Profiles
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT 'Learner',
  avatar_url TEXT,
  current_level INTEGER NOT NULL DEFAULT 1 CHECK (current_level BETWEEN 1 AND 10),
  completed_levels JSONB NOT NULL DEFAULT '[]'::jsonb,
  streak_count INTEGER NOT NULL DEFAULT 0,
  last_practice_date DATE,
  total_questions_answered INTEGER NOT NULL DEFAULT 0,
  total_score_sum REAL NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Practice Sessions
CREATE TABLE IF NOT EXISTS public.practice_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  level INTEGER NOT NULL CHECK (level BETWEEN 1 AND 10),
  mode TEXT NOT NULL DEFAULT 'level' CHECK (mode IN ('level', 'daily', 'random')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
  questions_count INTEGER NOT NULL DEFAULT 5,
  completed_count INTEGER NOT NULL DEFAULT 0,
  average_score REAL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ
);

-- 3. Question History (Prevents Repeating Questions Across Sessions)
CREATE TABLE IF NOT EXISTS public.question_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  session_id BIGINT NOT NULL REFERENCES public.practice_sessions(id) ON DELETE CASCADE,
  question_uid UUID NOT NULL DEFAULT gen_random_uuid(),
  level INTEGER NOT NULL CHECK (level BETWEEN 1 AND 10),
  topic TEXT NOT NULL,
  question_text TEXT NOT NULL,
  normalized_hash TEXT NOT NULL,
  hint_text TEXT,
  example_answer TEXT,
  order_index INTEGER NOT NULL DEFAULT 0,
  user_answer TEXT,
  input_mode TEXT CHECK (input_mode IN ('voice', 'text')),
  grammar_score REAL,
  vocabulary_score REAL,
  structure_score REAL,
  overall_score REAL,
  ai_feedback JSONB,
  answered_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_question_history_user_hash
  ON public.question_history(user_id, normalized_hash);

-- 4. AI Conversation Threads
CREATE TABLE IF NOT EXISTS public.conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  topic TEXT NOT NULL,
  level INTEGER NOT NULL DEFAULT 3,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.conversation_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('ai', 'user')),
  content TEXT NOT NULL,
  correction TEXT,
  hindi_tip TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Vocabulary Practice History
CREATE TABLE IF NOT EXISTS public.vocabulary_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  word TEXT NOT NULL,
  part_of_speech TEXT NOT NULL,
  pronunciation TEXT NOT NULL,
  english_meaning TEXT NOT NULL,
  hindi_meaning TEXT NOT NULL,
  example_sentence TEXT NOT NULL,
  level INTEGER NOT NULL DEFAULT 1,
  mastered BOOLEAN NOT NULL DEFAULT FALSE,
  practice_date DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. Daily English Challenge Tracking
CREATE TABLE IF NOT EXISTS public.daily_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  challenge_date DATE NOT NULL DEFAULT CURRENT_DATE,
  session_id BIGINT NOT NULL REFERENCES public.practice_sessions(id) ON DELETE CASCADE,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  average_score REAL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(user_id, challenge_date)
);

-- Enable Row Level Security (RLS) on all tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.practice_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.question_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vocabulary_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_challenges ENABLE ROW LEVEL SECURITY;

-- Strict User-Owned RLS Policies
CREATE POLICY "Users manage own profile"
  ON public.profiles FOR ALL USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

CREATE POLICY "Users manage own sessions"
  ON public.practice_sessions FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users manage own question history"
  ON public.question_history FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users manage own conversations"
  ON public.conversations FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users manage own conversation messages"
  ON public.conversation_messages FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.conversations c
      WHERE c.id = conversation_id AND c.user_id = auth.uid()
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.conversations c
      WHERE c.id = conversation_id AND c.user_id = auth.uid()
    )
  );

CREATE POLICY "Users manage own vocabulary"
  ON public.vocabulary_history FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users manage own daily challenges"
  ON public.daily_challenges FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
